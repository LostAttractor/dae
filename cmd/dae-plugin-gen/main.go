// dae-plugin-gen generates the build's plugin registry from local configuration.
package main

import (
	"bytes"
	"errors"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

const (
	configFile  = "plugins.cfg"
	exampleFile = "plugins.cfg.example"
	outputFile  = "internal/compiledplugins/plugins_generated.go"
)

// Go checks import paths and Plugin definitions at compile time.
func generate(data []byte) ([]byte, error) {
	var out, setups bytes.Buffer
	fmt.Fprintln(&out, "// Code generated by dae-plugin-gen; DO NOT EDIT.")
	fmt.Fprintln(&out, "//go:build linux\n\npackage compiledplugins")
	fmt.Fprintln(&out, "\nimport (\n\"github.com/daeuniverse/dae/component/plugin\"")
	validName := regexp.MustCompile(`^[a-z][a-z0-9_-]*$`)
	seen := make(map[string]int)
	for line, text := range strings.Split(string(data), "\n") {
		value, _, _ := strings.Cut(text, "#")
		if strings.TrimSpace(value) == "" {
			continue
		}
		name, path, ok := strings.Cut(value, ":")
		name, path = strings.TrimSpace(name), strings.TrimSpace(path)
		if !ok || name == "" || path == "" {
			return nil, fmt.Errorf("line %d: expected <type>:<Go import path>", line+1)
		}
		if !validName.MatchString(name) || name == "ca" || name == "status" || name == "help" {
			return nil, fmt.Errorf("line %d: invalid or reserved plugin command name %q", line+1, name)
		}
		if first, exists := seen[name]; exists {
			return nil, fmt.Errorf("line %d: duplicate plugin type %q (first declared on line %d)", line+1, name, first)
		}
		seen[name] = line + 1
		fmt.Fprintf(&out, "plugin%d %q\n", line, path)
		fmt.Fprintf(&setups, "%q: plugin%d.Plugin,\n", name, line)
	}
	fmt.Fprintln(&out, ")\n\n// Definitions returns the plugins selected for this build.\nfunc Definitions() map[string]plugin.Definition {\nreturn map[string]plugin.Definition{")
	out.Write(setups.Bytes())
	fmt.Fprintln(&out, "}\n}")
	return format.Source(out.Bytes())
}

func run() error {
	source := configFile
	data, err := os.ReadFile(source)
	if errors.Is(err, os.ErrNotExist) {
		source = exampleFile
		data, err = os.ReadFile(source)
	}
	if err != nil {
		return err
	}
	data, err = generate(data)
	if err != nil {
		return fmt.Errorf("%s: %w", source, err)
	}
	if err := os.MkdirAll(filepath.Dir(outputFile), 0755); err != nil {
		return err
	}
	return os.WriteFile(outputFile, data, 0644)
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "dae-plugin-gen:", err)
		os.Exit(1)
	}
}
