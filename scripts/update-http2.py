#!/usr/bin/env python3
"""Reproduce dae's HTTP/2 package from an official Go toolchain."""

import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import tempfile


ROOT = Path(__file__).resolve().parent.parent
DEST = ROOT / "internal/http2"
PATCH = ROOT / "scripts/http2/request-metadata.patch"
MARKER = "// Code generated by scripts/update-http2.py; DO NOT EDIT.\n"


def generate(goroot, output):
    version = (goroot / "VERSION").read_text().splitlines()[0]
    source = goroot / "src/net/http/internal"
    files = {}
    for package, destination in (("http2", ""), ("httpcommon", "internal/httpcommon"), ("httpsfv", "internal/httpsfv")):
        for path in sorted((source / package).glob("*.go")):
            if path.name.endswith("_test.go"):
                continue
            relative = str(Path(destination) / path.name)
            data = path.read_bytes()
            files[relative] = {
                "source": str(path.relative_to(goroot)),
                "sha256": hashlib.sha256(data).hexdigest(),
            }
            text = data.decode()
            for name in ("httpcommon", "httpsfv"):
                text = text.replace('"net/http/internal/' + name + '"',
                                    '"github.com/daeuniverse/dae/internal/http2/internal/' + name + '"')
            # Use the public net/http sentinels and content sniffer. Keeping
            # their identity is essential for ReverseProxy's ErrAbortHandler.
            text = text.replace('"net/http/internal"', 'internal "net/http"')
            text = text.replace("internal.ErrRequestCanceled", 'errors.New("net/http: request canceled")')
            if "internal." not in text:
                text = text.replace('\tinternal "net/http"\n', '')
            text = text.replace("//go:generate ", "// Upstream generator: ")
            target = output / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(MARKER + text)
    if not files:
        raise SystemExit("Go source tree has no net/http/internal/http2 implementation")
    if not PATCH.is_file() or not PATCH.stat().st_size:
        raise SystemExit("missing HTTP/2 request metadata patch")
    subprocess.run(["git", "apply", "--", str(PATCH)], cwd=output, check=True)
    subprocess.run([str(goroot / "bin/gofmt"), "-w", *[str(output / name) for name in files]], check=True)
    (output / "LICENSE").write_bytes((goroot / "LICENSE").read_bytes())
    manifest = {
        "version": version,
        "upstream": "https://go.googlesource.com/go/+/%s/src/net/http/internal/http2" % version,
        "files": files,
    }
    (output / "upstream.json").write_text(json.dumps(manifest, indent=2) + "\n")
    return {*files, "LICENSE", "upstream.json"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--goroot", type=Path, help="official Go source root (defaults to go env GOROOT)")
    parser.add_argument("--check", action="store_true", help="verify the pinned source and patch reproduce checked-in files")
    args = parser.parse_args()
    goroot = args.goroot or Path(subprocess.check_output(["go", "env", "GOROOT"], text=True).strip())
    with tempfile.TemporaryDirectory(prefix="dae-http2-") as directory:
        output = Path(directory)
        names = generate(goroot, output)
        if args.check:
            differences = sorted(name for name in names if not (DEST / name).exists() or
                                 (DEST / name).read_bytes() != (output / name).read_bytes())
            if differences:
                raise SystemExit("HTTP/2 generated files differ: " + ", ".join(differences))
            print("HTTP/2 source and patch are reproducible")
            return
        previous = DEST / "upstream.json"
        if previous.exists():
            for name in set(json.loads(previous.read_text())["files"]) - names:
                path = DEST / name
                if path.read_text().startswith(MARKER):
                    path.unlink()
        for name in sorted(names):
            target = DEST / name
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes((output / name).read_bytes())
        print("Updated HTTP/2 from " + (goroot / "VERSION").read_text().splitlines()[0])


if __name__ == "__main__":
    main()
